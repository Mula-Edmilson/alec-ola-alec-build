import assert from 'node:assert/strict';
import {localTextOnly,localContextWindow,estimateText,conversationBudget,fitLocalText,compactAlecGuide} from './alec-local-context.mjs';
const omni={id:'local:LFM3-Omni-2B',supportsImages:true,supportsTools:true,maxOutputTokens:4096};
assert.ok(localTextOnly(omni));assert.equal(localContextWindow(omni,32768),2048);
assert.equal(localContextWindow(omni,1024),1024);
assert.ok(!localTextOnly({id:'other',supportsImages:true,supportsTools:true}));
assert.ok(localTextOnly({id:'small',supportsImages:false,supportsTools:false}));
const sys=compactAlecGuide('ALEC')+'\nÉs um assistente útil. Responde em português. Sem ferramentas.';
const budget=conversationBudget(omni,32768,sys);
assert.ok(budget>400&&budget<1500);
const original=Array.from({length:40},(_,i)=>({role:i%2?'assistant':'user',content:'Histórico '+i+' '+('conversa anterior '.repeat(40))}));
original.push({role:'user',content:'Olá, tudo bem?'});
const saved=JSON.stringify(original);const result=fitLocalText(original,budget);
assert.deepEqual(result.at(-1),original.at(-1));assert.equal(JSON.stringify(original),saved);
assert.ok(result.reduce((n,m)=>n+estimateText(m.content),0)<=budget);
assert.equal(result[0].role,'user');
const long={role:'user',content:'x'.repeat(6000)};assert.deepEqual(fitLocalText([...original,long],budget),[long]);
assert.ok(estimateText(long.content)>budget);assert.ok(estimateText('Olá')>estimateText('O'));
console.log('Local context: LFM3 Omni, window caps, UTF-8 estimate, last-turn preservation, immutable history and oversized request gate passed.');
